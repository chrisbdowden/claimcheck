"""Copy the engine and sample data into service/ for the Vercel API.

The API deploys from service/ with slim dependencies (no Streamlit), so it
carries its own copy of the engine. This script makes that copy; the test
tests/test_service_sync.py fails if the copy ever drifts from src/.

    python scripts/sync_service.py          # write the copy
    python scripts/sync_service.py --check  # exit 1 if out of date
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SERVICE = ROOT / "service"

# source -> destination (relative to ROOT)
FILES = {
    "src/__init__.py": "service/claimcheck_engine/__init__.py",
    "src/policy.py": "service/claimcheck_engine/policy.py",
    "src/rules.py": "service/claimcheck_engine/rules.py",
    "src/ai_review.py": "service/claimcheck_engine/ai_review.py",
    "src/evaluate.py": "service/claimcheck_engine/evaluate.py",
    "src/pipeline.py": "service/claimcheck_engine/pipeline.py",
    "data/expenses.csv": "service/data/expenses.csv",
    "data/policy.csv": "service/data/policy.csv",
}
HEADER = "# GENERATED by scripts/sync_service.py from {src}. Edit the original, then re-run the script.\n"


def expected(src: str) -> bytes:
    data = (ROOT / src).read_bytes()
    if src.endswith(".py"):
        return HEADER.format(src=src).encode() + data
    return data


def out_of_date() -> list[str]:
    stale = []
    for src, dst in FILES.items():
        target = ROOT / dst
        if not target.exists() or target.read_bytes() != expected(src):
            stale.append(dst)
    return stale


def main() -> int:
    if "--check" in sys.argv:
        stale = out_of_date()
        for path in stale:
            print(f"out of date: {path}")
        if stale:
            print("Run: python scripts/sync_service.py")
        return 1 if stale else 0
    for src, dst in FILES.items():
        target = ROOT / dst
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(expected(src))
        print(f"synced {src} -> {dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
